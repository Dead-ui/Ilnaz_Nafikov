# ЗАДАНИЕ 8 (со звёздочкой). Парсер команд для квеста
# Собери мини-обработчик команд:
# 1. Спроси у пользователя команду через input().
# 2. Приведи к нижнему регистру и убери пробелы (.lower().strip()).
# 3. Разбей через .split().
# 4. Если слов нет — напечатай "Ты ничего не сказал."
# 5. Иначе достань действие (первое слово).
# 6. Если действие == "взять" -> "Ты берёшь предмет."
#    Если действие == "идти" -> "Ты идёшь."
#    Если действие == "осмотреть" -> "Ты осматриваешься."
#    Иначе -> "Я не понял."

# Напиши код здесь:

user_input = input("Введите команду: ")

words = user_input.lower().strip().split()

if len(words) == 0:
    print("Ты ничего не сказал.")
else:
    action = words[0]

    if action == "взять":
        print("Ты берёшь предмет.")
    elif action == "идти":
        print("Ты идёшь.")
    elif action == "осмотреть":
        print("Ты осматриваешься.")
    else:
        print("Я не понял.")