# ЗАДАНИЕ 9 (со звёздочкой). Полный цикл работы с инвентарём
# Собери мини-игру:
# 1. Создай пустой инвентарь.
# 2. В цикле спрашивай у пользователя: "подобрать" или "инвентарь" или "выход".
# 3. Если "подобрать" — спроси название предмета и добавь через .append().
# 4. Если "инвентарь" — покажи все предметы через for.
# 5. Если "выход" — выйди из цикла (break).

# Напиши код здесь:

inventory = []

while True:
    choice = input("Введите действие ('подобрать', 'инвентарь', 'выход'): ").strip().lower()

    if choice == "подобрать":
        item = input("Введите название предмета: ")
        inventory.append(item)
        print(f"Предмет '{item}' добавлен в инвентарь.")
    elif choice == "инвентарь":
        print("Твой инвентарь:")
        for item in inventory:
            print(f"- {item}")
    elif choice == "выход":
        print("Выход из игры.")
        break
    else:
        print("Неизвестная команда, попробуйте снова.")